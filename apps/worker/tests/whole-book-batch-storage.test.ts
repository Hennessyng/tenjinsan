import { DatabaseSync } from "node:sqlite"
import {
  AnalysisRevision,
  bookMapProjection,
  ChapterPartMap,
  contentDigest,
  WholeBookPreparation,
} from "@reading-studio/contracts"
import { planBatchedVerification } from "@reading-studio/generation"
import { afterEach, expect, it } from "vitest"
import { z } from "zod"
import { batchRuntimeFixture, finishBatchRuntime } from "./whole-book-batch-runtime-fixture.ts"

const fixtures: Awaited<ReturnType<typeof batchRuntimeFixture>>[] = []
afterEach(async () => {
  for (const item of fixtures.splice(0)) await item.fixture.close()
})
async function prepared() {
  const item = await batchRuntimeFixture()
  fixtures.push(item)
  const { analysis } = await finishBatchRuntime(item)
  const data = analysis.wholeBook,
    state = data?.batched
  if (!data || !state?.manifest) throw new TypeError("Missing persisted state")
  return { item, analysis, data, state, manifest: state.manifest }
}

it.each(["missing", "foreign", "order", "duplicate"] as const)(
  "rejects %s matrix receipts instead of accepting a partial successful record",
  async (mode) => {
    const { item, analysis, data, state } = await prepared()
    const first = state.receipts[0]
    if (!first) throw new TypeError("Missing receipt")
    const receipts =
      mode === "missing"
        ? state.receipts.slice(1)
        : mode === "order"
          ? [...state.receipts].reverse()
          : mode === "duplicate"
            ? [first, first, ...state.receipts.slice(2)]
            : [{ ...first, targetId: "0".repeat(64) }, ...state.receipts.slice(1)]
    const before = item.fixture.storage.counts()
    expect(() =>
      item.fixture.storage.workflow.appendAnalysis({
        record: {
          ...analysis,
          id: "forged-results",
          wholeBook: { ...data, batched: { ...state, receipts } },
        },
        parentRevisionId: null,
      }),
    ).toThrow()
    expect(item.fixture.storage.counts()).toEqual(before)
  },
)

it.each(["append", "read", "cache"] as const)(
  "rejects a schema-valid fully rehashed map/target substitution on %s against actual completed jobs",
  async (mode) => {
    const { item, analysis, data, state, manifest } = await prepared()
    const maps = manifest.maps.map((map) =>
      ChapterPartMap.parse({
        ...map,
        summary: { ...map.summary, text: "Rehashed but not generated by its recorded job" },
      }),
    )
    const replanned = planBatchedVerification(
      { ...item.execution, setup: item.setup },
      { reserve: item.reserve, windows: item.windows },
      { maps, synthesis: manifest.synthesis },
    )
    if (replanned.kind !== "ready") throw new TypeError("Failed to construct schema-valid tamper")
    const replacement = replanned.manifest
    const wholeBook = WholeBookPreparation.parse({
      ...data,
      maps,
      batched: {
        ...state,
        manifest: replacement,
        manifestHash: contentDigest(JSON.stringify(replacement)),
        receipts: state.receipts.map((receipt, index) => ({
          ...receipt,
          targetId: replacement.targets[index]?.id,
        })),
      },
    })
    const projection = bookMapProjection(wholeBook)
    const forged = AnalysisRevision.parse({ ...analysis, ...projection, wholeBook })
    if (mode === "append") {
      expect(() =>
        item.fixture.storage.workflow.appendAnalysis({
          record: { ...forged, id: "forged-rehashed" },
          parentRevisionId: null,
        }),
      ).toThrow()
      return
    }
    const db = new DatabaseSync(item.fixture.databasePath)
    try {
      for (const row of db
        .prepare(
          "SELECT name FROM sqlite_master WHERE type='trigger' AND tbl_name='analysis_revisions'",
        )
        .all()) {
        const { name } = z.object({ name: z.string().regex(/^[a-zA-Z0-9_]+$/u) }).parse(row)
        db.exec(`DROP TRIGGER "${name}"`)
      }
      db.prepare("UPDATE analysis_revisions SET record_json=? WHERE id=?").run(
        JSON.stringify(forged),
        analysis.id,
      )
    } finally {
      db.close()
    }
    expect(() =>
      mode === "read"
        ? item.fixture.storage.workflow.getAnalysis(analysis.id)
        : item.fixture.storage.workflow.findSuccessfulAnalysis(analysis.cacheKey),
    ).toThrow()
  },
)
